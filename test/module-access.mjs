import assert from 'node:assert/strict';
import {MODULES,apiModule,effectiveModules,validateModuleAccess} from '../src/module-access.js';
assert.equal(apiModule('/api/campaigns/12'), 'campaigns');
assert.equal(apiModule('/api/journeys/12'), 'sequences');
assert.equal(apiModule('/api/outreach/12'), 'outreach');
assert.equal(apiModule('/api/ads/12'), 'ads');
assert.equal(apiModule('/api/finance/summary'), 'pay');
assert.equal(apiModule('/api/crm/boards'), 'pipeline');
const agent=effectiveModules({role:'agent',permissions:{modules:{outreach:true,pay:false}}},[]);
assert.equal(agent.inbox,true);
assert.equal(agent.pipeline,true);
assert.equal(agent.outreach,true);
assert.equal(agent.pay,false);
assert.equal(agent.sequences,false);
const team=effectiveModules({role:'agent',permissions:{}},[{module_access:{sequences:true,ads:false}}]);
assert.equal(team.sequences,true);
assert.equal(team.ads,false);
const licensed=effectiveModules({role:'owner',permissions:{}},[],{pay:false,outreach:false});
assert.equal(licensed.pay,false);
assert.equal(licensed.outreach,false);
assert.equal(licensed.governance,true);
assert.equal(licensed.inbox,true);
assert.deepEqual(validateModuleAccess({inbox:true,sequences:false}),{inbox:true,sequences:false});
assert.throws(()=>validateModuleAccess({unknown:true}),/Área ou acesso inválido/);
assert.throws(()=>validateModuleAccess({pay:'yes'}),/Área ou acesso inválido/);
assert.ok(Object.keys(MODULES).includes('outreach'));
console.log('Module access regression checks passed');
