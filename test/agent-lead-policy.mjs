import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {connectionInput} from '../src/connection-policy.js';
import {leadPayload,verifyLeadSignature} from '../src/lead-payload.js';
import {renderFieldVariables,conversationVariables} from '../src/customer-variables.js';
const valid={name:'Consulta',url:'https://api.example.com/lookup',method:'GET',parameters:[{name:'document',description:'Documento confirmado'}]};
assert.equal(connectionInput(valid).method,'GET');
for(const change of [{url:'http://example.com'},{url:'https://user:pass@example.com'},{url:'https://example.com:8443'},{method:'DELETE'},{parameters:[{name:'__proto__'}]},{parameters:[{name:'id'},{name:'id'}]}])assert.throws(()=>connectionInput({...valid,...change}));
const payload={type:'form',external_id:'one',handle:'IG:100',page:'https://example.com/form?email=private#anchor',fields:{vehicle:'Caminhonete'}};
assert.equal(leadPayload(payload).page,'https://example.com/form');
assert.equal(leadPayload(payload).handle,'IG:100');
for(const change of [{type:'unknown'},{handle:''},{fields:[]},{page:'javascript:alert(1)'},{fields:{huge:'a'.repeat(17000)}}])assert.throws(()=>leadPayload({...payload,...change}));
const body=Buffer.from(JSON.stringify(payload)),timestamp=1700000000,secret='test-secret',signature='sha256='+crypto.createHmac('sha256',secret).update(timestamp+'.').update(body).digest('hex');
assert.ok(verifyLeadSignature(secret,body,timestamp,signature,timestamp*1000));
assert.equal(verifyLeadSignature(secret,Buffer.from('{}'),timestamp,signature,timestamp*1000),false);
assert.equal(verifyLeadSignature(secret,body,timestamp,signature,(timestamp+301)*1000),false);
assert.equal(verifyLeadSignature(secret,body,timestamp,'invalid',timestamp*1000),false);
const q=async sql=>({rows:sql.includes('custom_fields,data')?[{custom_fields:{},data:{lead_origin:{source:'Formulário',campaign:'Frota'},qualification:{status:'qualified',score:80}}}]:[]});
const vars=await conversationVariables(q,{id:1,contact_id:1});
assert.equal(vars.values.lead.origem,'Formulário');
assert.equal(renderFieldVariables('{{lead.origem}} · {{lead.pontuacao}}',vars.values),'Formulário · 80');
assert.equal(renderFieldVariables('{{lead.constructor}}',vars.values),'');
console.log('OK: políticas de conexão, assinatura/expiração, payload e variáveis de lead');
